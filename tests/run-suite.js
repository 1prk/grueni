/* Runs the browser test suite in Node.
   The script list comes from tests/index.html. So Node and the browser run the same files.
     node tests/run-suite.js                   run all tests
     node tests/run-suite.js --update-golden   write tests/golden/golden-data.js (after an intended change) */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const html = fs.readFileSync(path.join(__dirname, 'index.html'), 'utf8');
const scripts = Array.from(html.matchAll(/<script src="([^"]+)"><\/script>/g)).map(m => m[1])
  .filter(src => src !== 'runner-browser.js');

const ctx = { console, Date, Math, JSON, TextEncoder, TextDecoder };
ctx.window = {};
vm.createContext(ctx);
for (const src of scripts) {
  const file = path.join(__dirname, src);
  vm.runInContext(fs.readFileSync(file, 'utf8'), ctx, { filename: file });
}
const GZT = ctx.window.GZT;

(async () => {
  if (process.argv.includes('--update-golden')) {
    const golden = GZT.computeGolden();
    const out = path.join(__dirname, 'golden', 'golden-data.js');
    fs.writeFileSync(out, '/* Generated by: node tests/run-suite.js --update-golden. Do not edit by hand. */\n' +
      'window.GZT_GOLDEN = ' + JSON.stringify(golden, null, 1) + ';\n');
    console.log('wrote ' + path.relative(process.cwd(), out) + ' (' + Object.keys(golden).length + ' cases)');
    return;
  }
  const results = await GZT.runAll();
  let failed = 0;
  for (const r of results) {
    if (r.ok) console.log('ok   ' + r.name);
    else { failed++; console.log('FAIL ' + r.name + '\n     ' + r.error); }
  }
  console.log(failed ? `\n${failed} of ${results.length} tests failed` : `\nall ${results.length} tests passed`);
  process.exit(failed ? 1 : 0);
})();
